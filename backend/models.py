"""
models.py - SQLAlchemy ORM models (database table definitions).

Two core tables:
  - Event: every normalized log line stored here
  - Alert: security alerts generated by the detection engine
"""

from datetime import datetime
from sqlalchemy import Column, Integer, String, DateTime, Text
from database import Base


class Event(Base):
    """
    Normalized security event.
    Every raw log line from every source is converted into this common schema.
    This is the heart of SIEM normalization: different log formats become one structure.
    """
    __tablename__ = "events"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, nullable=False)
    source = Column(String(50), nullable=False)         # authentication / web / network
    event_type = Column(String(100), nullable=False)    # login_failed, http_request, etc.
    username = Column(String(100), nullable=True)
    source_ip = Column(String(45), nullable=True)
    destination_ip = Column(String(45), nullable=True)
    destination_port = Column(Integer, nullable=True)
    http_method = Column(String(10), nullable=True)
    endpoint = Column(String(500), nullable=True)
    status_code = Column(Integer, nullable=True)
    status = Column(String(50), nullable=True)          # success / failure / blocked
    severity = Column(String(20), nullable=False, default="low")
    raw_log = Column(Text, nullable=False)              # Original log line always preserved
    created_at = Column(DateTime, default=datetime.utcnow)


class Alert(Base):
    """
    Security alert generated by the detection engine.
    Alerts are the output of applying detection rules to normalized events.
    A single alert can represent multiple related events (e.g., 5 failed logins).
    """
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, index=True)
    alert_type = Column(String(100), nullable=False)    # BRUTE_FORCE_ATTACK, PORT_SCAN, etc.
    severity = Column(String(20), nullable=False)       # CRITICAL / HIGH / MEDIUM / LOW
    source_ip = Column(String(45), nullable=True)
    description = Column(Text, nullable=False)
    event_count = Column(Integer, default=1)
    first_seen = Column(DateTime, nullable=False)
    last_seen = Column(DateTime, nullable=False)
    status = Column(String(30), default="OPEN")         # OPEN / INVESTIGATING / RESOLVED / FALSE_POSITIVE
    rule_id = Column(String(50), nullable=False)        # e.g., AUTH-001
    created_at = Column(DateTime, default=datetime.utcnow)
